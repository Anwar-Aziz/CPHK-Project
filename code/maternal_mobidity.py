def mice_with_categorical_mode(df, max_iter=10, plot_convergence=True):
    """Apply MICE to numeric and mode imputation to categorical features."""

    df_imputed = df.copy()

    # 🔢 Separate numeric and categorical columns
    numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
    categorical_cols = df.select_dtypes(include=['object', 'category']).columns.tolist()

    # 🧠 Check if numeric columns are enough
    if len(numeric_cols) < 2:
        print("⚠️  Not enough numeric columns for MICE imputation")
        return df

    print(f"🔄 Running MICE imputation on {len(numeric_cols)} numeric columns...")
    print(f"📊 Numeric Columns: {numeric_cols}")
    print(f"🧾 Categorical Columns (mode): {categorical_cols}")

    # 🔁 MICE Imputation on numeric
    mice_imputer = IterativeImputer(
        estimator=RandomForestRegressor(n_estimators=10, random_state=42),
        max_iter=max_iter,
        random_state=42,
        verbose=1 if max_iter > 5 else 0
    )

    original_missing = df[numeric_cols].isnull().sum()
    imputed_numeric = mice_imputer.fit_transform(df[numeric_cols])
    df_imputed[numeric_cols] = imputed_numeric

    # 🔠 Mode Imputation on categorical
    if categorical_cols:
        mode_imputer = SimpleImputer(strategy='most_frequent')
        df_imputed[categorical_cols] = mode_imputer.fit_transform(df[categorical_cols])

    # 📊 Visualization for numeric (optional)
    if plot_convergence:
        n_cols = min(4, len(numeric_cols))
        fig, axes = plt.subplots(2, 2, figsize=(15, 10))
        axes = axes.flatten()

        for i, col in enumerate(numeric_cols[:n_cols]):
            ax = axes[i]

            original_data = df[col].dropna()
            if len(original_data) > 0:
                ax.hist(original_data, alpha=0.5, label='Original', bins=20, density=True)

            ax.hist(df_imputed[col], alpha=0.5, label='With Imputed', bins=20, density=True)
            ax.set_title(f'{col} - Distribution Comparison')
            ax.set_xlabel(col)
            ax.set_ylabel('Density')
            ax.legend()

            if len(original_data) > 0:
                ax.text(0.05, 0.95,
                        f'Original mean: {original_data.mean():.2f}\nImputed mean: {df_imputed[col].mean():.2f}',
                        transform=ax.transAxes,
                        verticalalignment='top',
                        bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.5))

        plt.tight_layout()
        plt.show()

    # 📈 Summary of imputation
    print(f"\n📈 IMPUTATION RESULTS:")
    for col in numeric_cols + categorical_cols:
        missing_before = df[col].isnull().sum()
        missing_after = df_imputed[col].isnull().sum()
        print(f"  {col:20}: {missing_before:4,} → {missing_after:4,} missing values")

    return df_imputed

