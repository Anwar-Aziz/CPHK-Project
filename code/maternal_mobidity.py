# Function to create variation tables
def create_variation_table(group_col, categories):
    table = pd.DataFrame(index=categories, columns=[f'{feature}_Has' for feature in binary_features] +
                         [f'{feature}_No' for feature in binary_features])

    for feature in binary_features:
        table[f'{feature}_Has'] = df_vis.groupby(group_col, observed=False)[feature].sum()
        table[f'{feature}_No'] = df_vis.groupby(group_col, observed=False)[feature].apply(lambda x: x.size - x.sum())

    table = table.fillna(0).astype(int)
    table['Category'] = table.index
    table['Group_Type'] = group_col
    table = table.reset_index(drop=True)

    # Add total row
    total_row = table.iloc[:, :-2].sum().to_frame().T
    total_row['Category'] = 'Total'
    total_row['Group_Type'] = group_col

    return pd.concat([table, total_row], ignore_index=True)

