def analyze_missing_mechanisms(df):
    """Analyze missing data patterns and mechanisms"""

    print("🔍 MISSING DATA MECHANISM ANALYSIS:")
    print("=" * 45)

    analysis = {}

    # Overall missing statistics
    total_cells = df.shape[0] * df.shape[1]
    missing_cells = df.isnull().sum().sum()
    analysis['overall_missing_rate'] = (missing_cells / total_cells) * 100

    # Column-wise missing analysis
    col_missing = df.isnull().sum()
    analysis['columns_with_missing'] = col_missing[col_missing > 0].to_dict()

    # Row-wise missing analysis
    row_missing = df.isnull().sum(axis=1)
    analysis['rows_with_missing'] = (row_missing > 0).sum()
    analysis['complete_rows'] = (row_missing == 0).sum()

    # Missing pattern analysis
    missing_patterns = df.isnull()
    pattern_counts = missing_patterns.value_counts()
    analysis['unique_missing_patterns'] = len(pattern_counts)
    analysis['most_common_pattern'] = pattern_counts.index[0] if len(pattern_counts) > 0 else None

    # Test for systematic missing patterns
    # Check age-related missing patterns (MAR example)
    if 'age' in df.columns and 'insurance_type' in df.columns:
        age_missing_by_insurance = df.groupby('insurance_type')['age'].apply(lambda x: x.isnull().mean())
        analysis['age_missing_by_insurance'] = age_missing_by_insurance.to_dict()

    return analysis

