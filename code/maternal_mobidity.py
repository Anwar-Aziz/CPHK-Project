def comprehensive_data_quality_assessment(df):
    """Perform comprehensive data quality assessment"""

    print("🔬 CUSTOM DATA QUALITY ASSESSMENT:")
    print("=" * 45)

    assessment = {}

    # Basic statistics
    assessment['total_records'] = len(df)
    assessment['total_columns'] = len(df.columns)

    # Completeness assessment
    completeness = (1 - df.isnull().sum() / len(df)) * 100
    assessment['completeness_by_column'] = completeness.to_dict()
    assessment['overall_completeness'] = completeness.mean()

    # Uniqueness assessment
    uniqueness = df.nunique() / len(df) * 100
    assessment['uniqueness_by_column'] = uniqueness.to_dict()

    # Data type distribution
    assessment['data_types'] = df.dtypes.value_counts().to_dict()

    # Duplicate assessment
    assessment['duplicate_records'] = df.duplicated().sum()
    assessment['duplicate_percentage'] = (df.duplicated().sum() / len(df)) * 100

    # Identify potential issues
    issues = []

    # High missing rate columns (>20%)
    high_missing = completeness[completeness < 80].index.tolist()
    if high_missing:
        issues.append(f"High missing rate (>20%) in columns: {high_missing}")

    # Low uniqueness in expected unique columns
    potential_id_cols = [col for col in df.columns if 'id' in col.lower()]
    for col in potential_id_cols:
        if col in uniqueness and uniqueness[col] < 95:
            issues.append(f"Low uniqueness in ID column '{col}': {uniqueness[col]:.1f}%")

    # High duplicate rate (>5%)
    if assessment['duplicate_percentage'] > 5:
        issues.append(f"High duplicate rate: {assessment['duplicate_percentage']:.1f}%")

    # Check for outliers in numerical columns
    numerical_cols = df.select_dtypes(include=[np.number]).columns
    for col in numerical_cols:
        if not df[col].empty:
            Q1 = df[col].quantile(0.25)
            Q3 = df[col].quantile(0.75)
            IQR = Q3 - Q1
            outliers = df[(df[col] < Q1 - 1.5*IQR) | (df[col] > Q3 + 1.5*IQR)][col].count()
            if outliers > len(df) * 0.05:  # More than 5% outliers
                issues.append(f"High outlier rate in '{col}': {outliers} ({outliers/len(df)*100:.1f}%)")

    assessment['identified_issues'] = issues

    return assessment

