# Selected binary feature
binary_feature = 'NEONATAL_DEATH'

# Function to create variation tables with total row
def create_variation_table(group_col, categories):
    table = pd.DataFrame(index=categories, columns=[f'{binary_feature}_Has', f'{binary_feature}_No'])

    table[f'{binary_feature}_Has'] = df_alive_transformed.groupby(group_col, observed=False)[binary_feature].sum()
    table[f'{binary_feature}_No'] = df_alive_transformed.groupby(group_col, observed=False)[binary_feature].apply(lambda x: x.size - x.sum())

    table = table.fillna(0).astype(int)
    table['Category'] = table.index
    table['Group_Type'] = group_col
    table = table.reset_index(drop=True)

    # Add total row
    total_row = table.iloc[:, :-2].sum().to_frame().T
    total_row['Category'] = 'Total'
    total_row['Group_Type'] = group_col

    return pd.concat([table, total_row], ignore_index=True)

